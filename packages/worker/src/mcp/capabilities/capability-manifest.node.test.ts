import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { personIdFromStored } from '@kody-internal/shared/owner-person-ids.ts'
import { expect, test, vi } from 'vitest'
import { createMcpCallerContext } from '#mcp/context.ts'
import { searchUnified } from '#mcp/tools/search.ts'
import {
	filterCapabilityRegistryForCaller,
	type CallerFeatureFlags,
} from './access-control.ts'
import { buildCapabilityRegistry } from './build-capability-registry.ts'
import {
	builtinDomainModuleLoaders,
	loadBuiltinDomainModule,
	loadBuiltinDomains,
} from './builtin-domains.ts'
import { capabilityManifest } from './capability-manifest.generated.mjs'
import type { Capability, DomainSpec } from './types.ts'

const manifestPath = fileURLToPath(
	new URL('./capability-manifest.generated.mjs', import.meta.url),
)

function loadRealDomains() {
	return Promise.all(
		Object.keys(builtinDomainModuleLoaders).map((name) =>
			loadBuiltinDomainModule(name),
		),
	)
}

function withoutHandler(capability: Capability) {
	return Object.fromEntries(
		Object.entries(capability).filter(
			([key, value]) => key !== 'handler' && value !== undefined,
		),
	)
}

function createManifest(domains: ReadonlyArray<DomainSpec>) {
	return {
		domains: domains.map(({ capabilities, ...domain }) => ({
			...domain,
			capabilities: capabilities.map(withoutHandler),
		})),
	}
}

function jsonClone<T>(value: T): T {
	return JSON.parse(JSON.stringify(value)) as T
}

function withoutHandlers(registry: ReturnType<typeof buildCapabilityRegistry>) {
	const { capabilityHandlers, capabilityMap, ...rest } = registry
	return jsonClone({
		...rest,
		capabilityList: rest.capabilityList.map(withoutHandler),
		capabilityMapNames: Object.keys(capabilityMap),
		capabilityHandlerNames: Object.keys(capabilityHandlers),
	})
}

/** Search output without wall-clock timings, which differ run to run. */
function withoutTimings(value: unknown): unknown {
	if (Array.isArray(value)) return value.map(withoutTimings)
	if (!value || typeof value !== 'object') return value
	return Object.fromEntries(
		Object.entries(value)
			.filter(([key]) => key !== 'phaseTimings' && !key.endsWith('Ms'))
			.map(([key, entry]) => [key, withoutTimings(entry)]),
	)
}

async function buildEagerAndManifestRegistries() {
	const [realDomains, manifestDomains] = await Promise.all([
		loadRealDomains(),
		loadBuiltinDomains(),
	])
	return {
		eager: buildCapabilityRegistry(realDomains),
		fromManifest: buildCapabilityRegistry(manifestDomains),
	}
}

test('the capability manifest matches the builtin domain definitions', async () => {
	const realDomains = await loadRealDomains()
	expect(realDomains.map((domain) => domain.name)).toEqual(
		Object.keys(builtinDomainModuleLoaders),
	)
	const expected = createManifest(realDomains)
	// Every derived artifact must survive JSON serialization unchanged.
	expect(jsonClone(expected)).toStrictEqual(expected)
	if (process.env.KODY_UPDATE_CAPABILITY_MANIFEST) {
		await writeFile(
			manifestPath,
			`// Generated by \`npm run capabilities:manifest\`. Do not edit.\nexport const capabilityManifest = ${JSON.stringify(expected, null, '\t')}\n`,
		)
		return
	}
	expect(
		jsonClone(capabilityManifest),
		'capability-manifest.generated.mjs is stale: run npm run capabilities:manifest',
	).toStrictEqual(expected)
})

test('the manifest registry matches the eager registry built from real definitions', async () => {
	const { eager, fromManifest } = await buildEagerAndManifestRegistries()
	expect(fromManifest.capabilityList.length).toBeGreaterThan(300)
	expect(withoutHandlers(fromManifest)).toStrictEqual(withoutHandlers(eager))
})

test('access filtering keeps the same capabilities for every caller shape', async () => {
	const { eager, fromManifest } = await buildEagerAndManifestRegistries()
	const flagKeys = [
		...new Set(
			eager.capabilityList.flatMap((capability) =>
				capability.featureFlag ? [capability.featureFlag] : [],
			),
		),
	]
	const allFlagsOn = Object.fromEntries(
		flagKeys.map((key) => [key, true]),
	) as CallerFeatureFlags
	const callerFor = (roles: Array<string> | null) =>
		createMcpCallerContext({
			source: { kind: 'mcp-oauth' },
			baseUrl: 'https://example.com',
			...(roles
				? {
						user: {
							userId: personIdFromStored('user-1'),
							email: 'user@example.com',
							displayName: 'User',
							roles,
						},
					}
				: {}),
		})
	const callers = [callerFor(null), callerFor([]), callerFor(['admin'])]
	const flagStates = [null, {} as CallerFeatureFlags, allFlagsOn]
	const sawDifferentSubsets = new Set<number>()
	for (const caller of callers) {
		for (const flags of flagStates) {
			const eagerNames = filterCapabilityRegistryForCaller(
				eager,
				caller,
				flags,
			).capabilityList.map((capability) => capability.name)
			const filtered = filterCapabilityRegistryForCaller(
				fromManifest,
				caller,
				flags,
			)
			expect(
				filtered.capabilityList.map((capability) => capability.name),
			).toEqual(eagerNames)
			expect(jsonClone(filtered.capabilitySpecs)).toStrictEqual(
				jsonClone(
					filterCapabilityRegistryForCaller(eager, caller, flags)
						.capabilitySpecs,
				),
			)
			sawDifferentSubsets.add(eagerNames.length)
		}
	}
	// The matrix must exercise role and flag gating, not only the full set.
	expect(sawDifferentSubsets.size).toBeGreaterThan(2)
})

test('search returns the same results from the manifest registry', async () => {
	const { eager, fromManifest } = await buildEagerAndManifestRegistries()
	const queries = [
		'list my secrets',
		'send an email',
		'create a job that runs every hour',
		'publish a package',
		'read a file',
		'storage sql query',
		'webhook',
		'invite someone to my org',
	]
	const search = (registry: typeof eager, query: string, domain?: string) =>
		searchUnified({
			env: {} as Env,
			query,
			limit: 10,
			registry,
			optionalRows: {
				packageRows: [],
				userSecretRows: [],
				userIntegrationRows: [],
			},
			...(domain ? { domain } : {}),
		})
	const searchResult = async (
		registry: typeof eager,
		query: string,
		domain?: string,
	) => withoutTimings(jsonClone(await search(registry, query, domain)))
	for (const query of queries) {
		expect(await searchResult(fromManifest, query)).toStrictEqual(
			await searchResult(eager, query),
		)
	}
	expect(await searchResult(fromManifest, 'list', 'secrets')).toStrictEqual(
		await searchResult(eager, 'list', 'secrets'),
	)
})

test('manifest handlers dispatch to the real capability handler', async () => {
	const realDomains = await loadRealDomains()
	const manifestDomains = await loadBuiltinDomains()
	const ctx = { marker: 'ctx' } as never
	for (const [index, domain] of manifestDomains.entries()) {
		const realCapabilities = new Map(
			realDomains[index]!.capabilities.map((capability) => [
				capability.name,
				capability,
			]),
		)
		for (const capability of domain.capabilities) {
			const real = realCapabilities.get(capability.name)!
			const result = { name: capability.name }
			const spy = vi.spyOn(real, 'handler').mockResolvedValue(result)
			const args = { input: capability.name }
			await expect(capability.handler(args, ctx)).resolves.toBe(result)
			expect(spy).toHaveBeenCalledWith(args, ctx)
			spy.mockRestore()
		}
	}
})
