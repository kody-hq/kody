const { getGitRemoteCapability } = await import('./get-git-remote.ts')

const personalOwner = {
	ownerUserId: ownerIdFromStored('user-1'),
	ownerScope: 'kentcdodds',
	ownerEmail: 'user-1@example.com',
	actorUserId: 'user-1',
}
const invalidInput = 'Invalid input for capability "packageGetGitRemote"'
const createRequiresLeaf =
	'`create: true` requires `name` (package name leaf or `@scope/leaf`) without `package_id`; new package ids are generated by Kody.'

function resetMocks() {
	for (const fn of Object.values(mockModule)) fn.mockReset()
	mockModule.resolvePackageOwnerContext.mockResolvedValue(personalOwner)
}

type GitRemoteResult = {
	expires_at: string
	authenticated_remote: string
	setup_commands: Array<string>
}

function callerContextWithScopes(
	scopes: Array<OrgPermission> | null,
	orgBinding?: { org: { id: string; slug: string | null }; role: 'owner' },
) {
	const callerContext = createMcpCallerContext({
		source: { kind: 'mcp-oauth' },
		baseUrl: 'https://heykody.dev',
		user: {
			userId: personIdFromStored('user-1'),
			email: 'user-1@example.com',
			displayName: 'user-1',
		},
		orgBinding,
	})
	if (!scopes || !callerContext.request) return callerContext
	return {
		...callerContext,
		request: {
			...callerContext.request,
			credential: { ...callerContext.request.credential, scopes },
		},
	}
}

async function getRemote(
	args: Record<string, unknown>,
	{
		snapshot = createPublishedSnapshot(),
		scopes = null,
		orgBinding,
	}: {
		snapshot?: unknown
		scopes?: Array<OrgPermission> | null
		orgBinding?: { org: { id: string; slug: string | null }; role: 'owner' }
	} = {},
) {
	const result = await getGitRemoteCapability.handler(args, {
		env: {
			APP_DB: {},
			BUNDLE_ARTIFACTS_KV: {
				async get(_key: string, type?: 'text' | 'json') {
					return type === 'json' ? snapshot : null
				},
			},
		} as unknown as Env,
		callerContext: callerContextWithScopes(scopes, orgBinding),
	})
	return result as GitRemoteResult
}

function createPublishedSnapshot() {
	return {
		version: 1,
		sourceId: 'source-1',
		repoId: 'package-package-1',
		entityKind: 'package',
		entityId: 'package-1',
		publishedCommit: 'commit-1',
		manifestPath: 'package.json',
		sourceRoot: '/',
		files: {
			'package.json': JSON.stringify({
				name: '@kentcdodds/unleashed-wifi',
				exports: { '.': './src/index.ts' },
				kody: {
					id: 'unleashed-wifi',
					description: 'Unleashed WiFi controls.',
				},
			}),
			'src/index.ts': 'export default async function main() {}\n',
		},
		createdAt: '2026-05-04T00:00:00.000Z',
	}
}

function mockPackageSource(sourceUserId = 'user-1') {
	const savedPackage = {
		id: 'package-1',
		userId: sourceUserId,
		kodyId: 'unleashed-wifi',
		name: '@kentcdodds/unleashed-wifi',
		sourceId: 'source-1',
	}
	mockModule.getSavedPackageById.mockResolvedValue(savedPackage)
	mockModule.resolveSavedPackageRef.mockResolvedValue(savedPackage)
	mockModule.getEntitySourceByIdForUser.mockImplementation(
		async (_db: unknown, input: { id: string; userId: string }) => {
			if (input.userId !== sourceUserId) return null
			return {
				id: 'source-1',
				user_id: sourceUserId,
				entity_kind: 'package',
				entity_id: 'package-1',
				repo_id: 'package-package-1',
				published_commit: 'commit-1',
				indexed_commit: null,
				manifest_path: 'package.json',
				source_root: '/',
				last_external_check_at: null,
				external_check_until: null,
				created_at: '2026-05-04T00:00:00.000Z',
				updated_at: '2026-05-04T00:00:00.000Z',
			}
		},
	)
	const createToken = vi.fn(async (scope: 'read' | 'write', ttl: number) => ({
		id: 'token-1',
		plaintext: `art_v1_${scope}_token?expires=${Math.floor(Date.now() / 1000) + ttl}`,
		scope,
		expiresAt: new Date(Date.now() + ttl * 1000).toISOString(),
	}))
	const remote =
		'https://acct.artifacts.cloudflare.net/git/default/package-package-1.git'
	mockModule.resolveExistingArtifactSourceRepo.mockResolvedValue({
		info: vi.fn(async () => ({ remote, defaultBranch: 'main' })),
		createToken,
	})
	mockModule.listServerRefs.mockResolvedValue([
		{ ref: 'refs/heads/main', oid: 'commit-1' },
	])
	return { createToken, remote }
}

function stubCreatedPackage(
	ownerUserId = 'user-1',
	name = '@kentcdodds/unleashed-wifi',
) {
	let remote: ReturnType<typeof mockPackageSource> | undefined
	mockModule.resolveSavedPackageRef.mockResolvedValueOnce(null)
	mockModule.createStubSavedPackage.mockImplementation(async () => {
		remote = mockPackageSource(ownerUserId)
		return { packageId: 'package-1', kodyId: 'unleashed-wifi', name }
	})
	return {
		get createToken() {
			return remote?.createToken
		},
	}
}

test('get_git_remote rejects invalid input before creating stubs', async () => {
	for (const [args, message] of [
		[{}, 'Provide exactly one of `package_id` or the package name leaf.'],
		[{ package_id: 'package-1', ttl_seconds: 59 }, invalidInput],
		[{ package_id: 'package-1', ttl_seconds: 86_401 }, invalidInput],
	] as const) {
		resetMocks()
		mockPackageSource()
		await expect(getRemote(args)).rejects.toThrow(message)
		expect(mockModule.createStubSavedPackage).not.toHaveBeenCalled()
	}

	for (const args of [
		{ package_id: 'package-1', create: true },
		{ create: true },
	] as const) {
		resetMocks()
		mockPackageSource()
		const createRequiresError = await getRemote(args).catch(
			(error: unknown) => error,
		)
		expect(createRequiresError).toBeInstanceOf(McpCallerError)
		expect(createRequiresError).toMatchObject({ message: createRequiresLeaf })
		expect(mockModule.createStubSavedPackage).not.toHaveBeenCalled()
	}

	resetMocks()
	const oversizeError = await getRemote({
		create: true,
		name: 'new-package',
		description: 'a'.repeat(KODY_DESCRIPTION_MAX_LENGTH + 1),
	}).catch((error: unknown) => error)
	expect(oversizeError).toBeInstanceOf(McpCallerError)
	expect(oversizeError).toMatchObject({
		message: expect.stringContaining(invalidInput),
	})
	expect(mockModule.createStubSavedPackage).not.toHaveBeenCalled()
	expect(mockModule.resolvePackageOwnerContext).not.toHaveBeenCalled()

	resetMocks()
	mockModule.getSavedPackageById.mockResolvedValue(null)
	await expect(getRemote({ package_id: 'missing' })).rejects.toThrow(
		'Saved package "missing" was not found in @kentcdodds, the org this connection is bound to. packageList lists the saved packages @kentcdodds owns with their package_id; to use a package another org owns, bind the connection to that org.',
	)

	resetMocks()
	mockPackageSource('other-user')
	await expect(getRemote({ package_id: 'package-1' })).rejects.toThrow(
		'Saved package "@kentcdodds/unleashed-wifi" (package_id package-1) is missing its repo source record "source-1". This is a missing source record, not an org-binding problem: the package row exists in @kentcdodds but its source does not. Repair the source record or recreate the package.',
	)
})

test('get_git_remote defaults to write when the caller can write', async () => {
	resetMocks()
	const { createToken, remote } = mockPackageSource()
	const before = Date.now()
	const defaultResult = await getRemote({
		package_id: 'package-1',
		ttl_seconds: 1800,
	})
	const defaultExpiresAt = new Date(defaultResult.expires_at).getTime()
	expect(createToken.mock.calls).toEqual([['write', 1800]])
	expect(
		mockModule.markEntitySourcePendingExternalReconcile,
	).toHaveBeenCalledWith(expect.anything(), {
		id: 'source-1',
		userId: ownerIdFromStored('user-1'),
		tokenExpiresAt: defaultResult.expires_at,
	})
	expect(defaultResult).toMatchObject({
		package_id: 'package-1',
		kody_id: 'unleashed-wifi',
		slug: 'unleashed-wifi',
		created: false,
		remote,
		scope: 'write',
		git_extra_header: 'Authorization: Bearer art_v1_write_token',
		git_author: { name: 'user-1', email: 'user-1@example.com' },
	})
	expect(defaultExpiresAt).toBeGreaterThanOrEqual(before + 1799 * 1000)
	expect(defaultExpiresAt).toBeLessThanOrEqual(Date.now() + 1801 * 1000)
	expect(defaultResult.authenticated_remote).toContain(
		'https://x:art_v1_write_token@',
	)
	expect(defaultResult.setup_commands.at(-1)).toMatch(/\bpush\b/)
	expect(mockModule.listServerRefs).toHaveBeenCalledWith(
		expect.objectContaining({
			protocolVersion: 1,
			prefix: 'refs/heads/main',
		}),
	)

	resetMocks()
	const readSetup = mockPackageSource()
	const readResult = await getRemote({
		name: 'unleashed-wifi',
		scope: 'read',
	})
	expect(readSetup.createToken.mock.calls).toEqual([['read', 14_400]])
	expect(readResult).toMatchObject({
		scope: 'read',
		remote: readSetup.remote,
		git_extra_header: 'Authorization: Bearer art_v1_read_token',
	})
	expect(readResult.authenticated_remote).toContain(
		'https://x:art_v1_read_token@',
	)
	expect(readResult.setup_commands.join('\n')).not.toMatch(/\bpush\b/)
	expect(
		mockModule.markEntitySourcePendingExternalReconcile,
	).not.toHaveBeenCalled()
})

test('get_git_remote defaults to read for read-only credentials and denies explicit write clearly', async () => {
	resetMocks()
	const { createToken } = mockPackageSource()
	await expect(
		getRemote({ package_id: 'package-1' }, { scopes: ['package:read'] }),
	).resolves.toMatchObject({ scope: 'read' })
	expect(createToken).toHaveBeenCalledWith('read', 14_400)

	createToken.mockClear()
	await expect(
		getRemote(
			{ package_id: 'package-1', scope: 'write' },
			{ scopes: ['package:read'] },
		),
	).rejects.toMatchObject({
		code: 'credential_scope',
		permission: 'package:write',
		message: expect.stringMatching(
			/You have read access to package @kentcdodds\/unleashed-wifi, not write[\s\S]*scope: 'read'[\s\S]*communityFork/,
		),
	})
	expect(createToken).not.toHaveBeenCalled()

	resetMocks()
	stubCreatedPackage()
	await expect(
		getRemote(
			{ name: 'unleashed-wifi', create: true, scope: 'read' },
			{ scopes: ['package:read'] },
		),
	).rejects.toMatchObject({
		code: 'credential_scope',
		permission: 'package:create',
	})
	expect(mockModule.createStubSavedPackage).not.toHaveBeenCalled()
})

test('get_git_remote retries remote timeouts and write scope blocks without a restorable backup snapshot', async () => {
	resetMocks()
	mockPackageSource()
	const timeout = new Error('Artifacts git request timed out after 8000ms.')
	timeout.name = 'ArtifactsGitTimeoutError'
	mockModule.listServerRefs.mockRejectedValue(timeout)
	await expect(getRemote({ package_id: 'package-1' })).rejects.toThrow(
		/packageGetGitRemote timed out reading the Artifacts git remote[\s\S]*packageSave/,
	)
	expect(mockModule.listServerRefs).toHaveBeenCalledTimes(3)

	resetMocks()
	mockPackageSource()
	await expect(
		getRemote({ package_id: 'package-1', scope: 'write' }, { snapshot: null }),
	).rejects.toThrow('Stop and report this source recovery problem')
})

test('get_git_remote create mode mints write for the new package from package:create alone', async () => {
	resetMocks()
	const stub = stubCreatedPackage()
	await expect(
		getRemote(
			{ name: 'unleashed-wifi', create: true },
			{ scopes: ['package:create', 'package:read'] },
		),
	).resolves.toMatchObject({ created: true, scope: 'write' })
	expect(stub.createToken).toHaveBeenCalledWith('write', 14_400)

	resetMocks()
	const readStub = stubCreatedPackage()
	await expect(
		getRemote(
			{ name: 'unleashed-wifi', create: true, scope: 'read' },
			{ scopes: ['package:create'] },
		),
	).resolves.toMatchObject({ created: true, scope: 'read' })
	expect(readStub.createToken).toHaveBeenCalledWith('read', 14_400)

	resetMocks()
	stubCreatedPackage()
	await expect(
		getRemote(
			{ name: 'unleashed-wifi', create: true, scope: 'write' },
			{ scopes: ['package:read', 'package:write'] },
		),
	).rejects.toMatchObject({
		code: 'credential_scope',
		permission: 'package:create',
	})
	// Create authorize runs before createStub so a denial leaves no orphan.
	expect(mockModule.createStubSavedPackage).not.toHaveBeenCalled()
})

test('get_git_remote create mode registers stubs for personal and org-bound owners', async () => {
	resetMocks()
	stubCreatedPackage()
	const createdResult = await getRemote({
		name: 'unleashed-wifi',
		create: true,
		description: 'WiFi controls',
	})
	expect(mockModule.createStubSavedPackage).toHaveBeenCalledWith(
		expect.objectContaining({
			kodyId: 'unleashed-wifi',
			description: 'WiFi controls',
			baseUrl: 'https://heykody.dev',
			owner: personalOwner,
		}),
	)
	expect(createdResult).toMatchObject({
		created: true,
		package_id: 'package-1',
		kody_id: 'unleashed-wifi',
		scope: 'write',
	})
	expect(createdResult.setup_commands.length).toBeGreaterThan(0)

	resetMocks()
	mockPackageSource()
	const existingResult = await getRemote({
		name: '@kentcdodds/unleashed-wifi',
		create: true,
	})
	expect(mockModule.createStubSavedPackage).not.toHaveBeenCalled()
	expect(existingResult).toMatchObject({
		created: false,
		package_id: 'package-1',
	})

	resetMocks()
	stubCreatedPackage()
	const trimmedResult = await getRemote({
		name: '  unleashed-wifi  ',
		create: true,
	})
	expect(mockModule.resolveSavedPackageRef).toHaveBeenNthCalledWith(
		1,
		expect.anything(),
		expect.objectContaining({ ref: 'unleashed-wifi' }),
	)
	expect(mockModule.createStubSavedPackage).toHaveBeenCalledWith(
		expect.objectContaining({ kodyId: 'unleashed-wifi' }),
	)
	expect(trimmedResult).toMatchObject({
		created: true,
		kody_id: 'unleashed-wifi',
	})

	resetMocks()
	stubCreatedPackage()
	const leftoverResult = await getRemote({
		kody_id: 'unleashed-wifi',
		create: true,
	})
	expect(leftoverResult).toMatchObject({
		created: true,
		kody_id: 'unleashed-wifi',
	})

	resetMocks()
	const bothError = await getRemote({
		name: 'unleashed-wifi',
		kody_id: 'unleashed-wifi',
		create: true,
	}).catch((error: unknown) => error)
	expect(bothError).toBeInstanceOf(McpCallerError)
	expect(bothError).toMatchObject({
		message: 'Provide `name` or leftover `kody_id`, not both. Prefer `name`.',
	})
	expect(mockModule.createStubSavedPackage).not.toHaveBeenCalled()

	resetMocks()
	const orgOwner = {
		ownerUserId: ownerIdFromStored('org-owner'),
		ownerScope: 'acme',
		ownerEmail: 'acme@example.com',
		actorUserId: 'user-1',
	}
	mockModule.resolvePackageOwnerContext.mockResolvedValue(orgOwner)
	stubCreatedPackage('org-owner', '@acme/unleashed-wifi')
	const orgResult = await getRemote(
		{
			name: 'unleashed-wifi',
			create: true,
		},
		{
			orgBinding: {
				org: { id: 'org-owner', slug: 'acme' },
				role: 'owner',
			},
		},
	)
	expect(mockModule.resolvePackageOwnerContext).toHaveBeenCalledWith(
		expect.anything(),
		expect.objectContaining({
			user: expect.objectContaining({ userId: ownerIdFromStored('user-1') }),
		}),
	)
	const ownerLookup = [
		expect.anything(),
		expect.objectContaining({
			userId: ownerIdFromStored('org-owner'),
			ref: 'unleashed-wifi',
		}),
	]
	expect(mockModule.resolveSavedPackageRef.mock.calls).toEqual([
		ownerLookup,
		ownerLookup,
	])
	expect(mockModule.createStubSavedPackage).toHaveBeenCalledWith(
		expect.objectContaining({
			owner: orgOwner,
			kodyId: 'unleashed-wifi',
		}),
	)
	expect(orgResult).toMatchObject({
		created: true,
		package_id: 'package-1',
	})
})
