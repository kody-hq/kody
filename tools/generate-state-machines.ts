import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { format } from 'oxfmt'
import {
	finalStatesOf,
	renderStateMachineMermaid,
	statesOf,
	type StateMachine,
	type StatusEnum,
	type LifecycleMachine,
} from '../packages/shared/src/state-machine.ts'
import { stateMachines, statusEnums } from './state-machines.ts'
import { isExecutedDirectly } from './node-runtime.ts'

export function renderStateMachines(
	entries: ReadonlyArray<{
		machine: StateMachine<string> | LifecycleMachine
		file: string
	}>,
	enums: ReadonlyArray<{ statusEnum: StatusEnum<string>; file: string }> = [],
): string {
	return `# Explicit state machines

<!-- Generated by tools/generate-state-machines.ts. Do not edit. -->

Owned lifecycles are migrating incrementally from legacy transition tables to
event-driven XState machines. Unconstrained replacement fields are status enums,
not state machines. Stored values and wire contracts remain unchanged.

Framework-owned request state (such as TanStack Query mutations) is used directly,
not wrapped in another machine. UI forms derive busy state from the mutation and
keep validation and receipt feedback as atomic discriminated values. App-owned
interaction controllers reject illegal transitions synchronously, including
submissions arriving before React has rendered a pending state.

## Adding a machine

Declare a flat XState machine next to the domain, with named operation events and
genuinely terminal states marked \`type: 'final'\`. Export the machine and a
\`LifecycleStateOf<typeof machine>\` alias, and register its machine and source path
in the package's \`state-machines.ts\` registry. The tooling-only aggregate at
\`tools/state-machines.ts\` includes each package registry without adding runtime
dependencies between packages. Run \`npm run state-machines:generate\`
and add focused graph tests. Existing stored values and wire contracts stay unchanged.

Use \`nextState(machine, from, event)\` for guard-aware transition validation and
\`sqlSourcesOf(machine, eventType)\` for SQL compare-and-set source lists. Sources
are structural: retain operation-specific SQL conditions alongside the list.
State-only helpers use static machine context unless explicit context is supplied;
machines with context initializers require explicit context. \`canHandle\` probes
with a type-only event; payload-dependent guards require \`nextState\` with the
full event. Legacy helpers remain available until their callers migrate.

Use \`defineStatusEnum\` for fields accepting arbitrary status replacement and
register them separately in \`statusEnums\`; they have no transition graph.

${entries
	.map(
		(
			{ machine, file },
			index,
		) => `${file.startsWith('packages/worker/client/') && !entries.slice(0, index).some((entry) => entry.file.startsWith('packages/worker/client/')) ? '## UI flows\n\n' : ''}## ${'getTransitionData' in machine ? machine.id : machine.name}

${'getTransitionData' in machine ? (machine.config.description ?? '') : machine.description}

Source: [\`${file}\`](../../${file})

States: ${('getTransitionData' in machine ? statesOf(machine) : machine.states).join(', ')}

Final states: ${('getTransitionData' in machine ? finalStatesOf(machine) : machine.terminal).join(', ') || 'None'}

\`\`\`mermaid
${renderStateMachineMermaid(machine)}
\`\`\`

${renderTransitions(machine)}
`,
	)
	.join('\n')}
## Status enums (not state machines)

${enums
	.map(
		({ statusEnum, file }) => `### ${statusEnum.name}

${statusEnum.description}

Source: [\`${file}\`](../../${file})

Values: ${statusEnum.values.join(', ')}
`,
	)
	.join('\n')}`
}

function renderTransitions(machine: StateMachine<string> | LifecycleMachine) {
	if (!('getTransitionData' in machine))
		return `Legacy transition table (no named events yet).

| State | May transition to |
| --- | --- |
${machine.states.map((state) => `| ${state} | ${machine.transitions[state]!.join(', ') || '— (terminal)'} |`).join('\n')}`
	return `| Event | From | To | Guard |
| --- | --- | --- | --- |
${statesOf(machine)
	.flatMap((state) =>
		[...machine.states[state]!.transitions].flatMap(([event, edges]) =>
			edges
				.filter((edge) => edge.target !== undefined || edge.actions.length > 0)
				.map(
					(edge) =>
						`| ${event} | ${state} | ${edge.target?.map((target) => target.key).join(', ') ?? state} | ${describeGuard(edge.guard)} |`,
				),
		),
	)
	.join('\n')}`
}

function describeGuard(guard: unknown): string {
	if (typeof guard === 'string') return guard
	if (typeof guard === 'function') return guard.name || 'inline'
	if (guard && typeof guard === 'object' && 'type' in guard)
		return String(guard.type)
	return '—'
}

if (isExecutedDirectly(import.meta.url)) {
	const path = resolve(
		import.meta.dirname,
		'../docs/contributing/state-machines.md',
	)
	const { code: rendered, errors } = await format(
		path,
		renderStateMachines(stateMachines, statusEnums),
		{ printWidth: 80, proseWrap: 'always', useTabs: true },
	)
	if (errors.length) throw new Error('Could not format state-machine reference')
	if (process.argv.includes('--check')) {
		if (readFileSync(path, 'utf8') !== rendered)
			throw new Error(
				'State-machine reference is stale. Run npm run state-machines:generate.',
			)
		console.log('State-machine reference is up to date.')
	} else {
		writeFileSync(path, rendered)
		console.log('Generated docs/contributing/state-machines.md')
	}
}
