#!/usr/bin/env node
/**
 * Refresh the vendored disposable-email domain list from
 * https://github.com/disposable-email-domains/disposable-email-domains
 * (`disposable_email_blocklist.conf`).
 *
 * Run from the repo root:
 *   node tools/update-disposable-email-domains.mjs
 *
 * Signup and account-email changes block the listed domains and any subdomain
 * of them. Major mailbox providers are dropped if they ever appear upstream so
 * a bad list cannot lock out gmail.com and the other protected domains below.
 */

import { spawnSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const sourceUrl =
	'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/master/disposable_email_blocklist.conf'

const outputPath = path.join(
	path.dirname(fileURLToPath(import.meta.url)),
	'../packages/worker/src/identity/disposable-email-domains.ts',
)

/** Never treat these as disposable, even if the upstream list contains them. */
const protectedDomains = [
	'aol.com',
	'example.com',
	'fastmail.com',
	'gmail.com',
	'googlemail.com',
	'hotmail.com',
	'icloud.com',
	'live.com',
	'me.com',
	'outlook.com',
	'proton.me',
	'protonmail.com',
	'yahoo.com',
]

const domainPattern =
	/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$/

function parseBlocklist(body) {
	const protectedSet = new Set(protectedDomains)
	const domains = new Set()
	const droppedProtected = []
	for (const line of body.split(/\r?\n/u)) {
		const trimmed = line.trim().toLowerCase()
		if (!trimmed || trimmed.startsWith('#')) continue
		const domain = trimmed.replace(/^\*\./u, '').replace(/\.$/u, '')
		if (!domainPattern.test(domain)) continue
		if (protectedSet.has(domain)) {
			droppedProtected.push(domain)
			continue
		}
		domains.add(domain)
	}
	return {
		domains: [...domains].sort(),
		droppedProtected,
	}
}

function renderModule(domains) {
	const lines = domains.map((domain) => `\t'${domain}',`)
	return `// Generated by tools/update-disposable-email-domains.mjs. Do not edit.
// Source: ${sourceUrl}
// Refresh: node tools/update-disposable-email-domains.mjs
// Domains: ${String(domains.length)}

export const disposableEmailDomainList = [
${lines.join('\n')}
] as const
`
}

const response = await fetch(sourceUrl)
if (!response.ok) {
	throw new Error(
		`Failed to download disposable email domains (${String(response.status)} ${response.statusText}).`,
	)
}
const parsed = parseBlocklist(await response.text())
if (parsed.domains.length < 1000) {
	throw new Error(
		`Disposable domain list is unexpectedly small (${String(parsed.domains.length)}). Refusing to overwrite the vendored copy.`,
	)
}
writeFileSync(outputPath, renderModule(parsed.domains))
const oxfmt = path.join(
	path.dirname(fileURLToPath(import.meta.url)),
	'../node_modules/.bin/oxfmt',
)
if (existsSync(oxfmt)) {
	const formatted = spawnSync(oxfmt, [outputPath], { stdio: 'inherit' })
	if (formatted.status !== 0) {
		throw new Error('oxfmt failed on the generated disposable domain list.')
	}
}
console.log(
	`Wrote ${String(parsed.domains.length)} domains to ${path.relative(process.cwd(), outputPath)}`,
)
if (parsed.droppedProtected.length > 0) {
	console.log(
		`Dropped protected domains: ${parsed.droppedProtected.join(', ')}`,
	)
}
