# Build the README result tables from results/summary.json. Usage: python3 readme-tables.py > results/readme-tables.md
import json, re, sys, os
d = json.load(open(os.path.join(os.path.dirname(__file__), '../results/summary.json')))
def f(x):
    if x is None: return ''
    a = abs(x)
    return f'{x:,.0f}' if a >= 100 else (f'{x:.1f}' if a >= 10 else (f'{x:.2f}' if a >= 0.1 or a == 0 else f'{x:.3f}'))
def cell(s):
    if not s or not s.get('n'): return 'n/a'
    return f"{f(s['median'])} (IQR {f(s['p75'] - s['p25'])}, CV {s['cv'] * 100:.0f}%)"
def delta(x):
    if not x: return 'n/a'
    return f"{f(x['diff'])} [{f(x['lo'])}, {f(x['hi'])}]" + (' noise' if x['withinNoise'] else '')
def table(section, keys=None, title=None, rng=False):
    sec = d[section]
    keys = [k for k in sec if keys is None or any(re.search(p, k) for p in keys)]
    out = [f'**{title or section}**', '', '| metric | n A/B/C | A | B | C | A to B | B to C | A to C |' + (' range A / B / C |' if rng else ''), '|---|---|---|---|---|---|---|---|' + ('---|' if rng else '')]
    for k in keys:
        st, de = sec[k].get('stats', {}), sec[k].get('deltas', {})
        n = '/'.join(str(st.get(v, {}).get('n', 0)) for v in 'abc')
        row = f"| {k} | {n} | {cell(st.get('a'))} | {cell(st.get('b'))} | {cell(st.get('c'))} | {delta(de.get('a->b'))} | {delta(de.get('b->c'))} | {delta(de.get('a->c'))} |"
        if rng: row += ' ' + ' / '.join(f"{f(st[v]['min'])} to {f(st[v]['max'])}" if v in st else 'n/a' for v in 'abc') + ' |'
        out.append(row)
    return '\n'.join(out) + '\n'
parts = [
    table('build', title='1a. Whole client build (bytes, one build per variant)'),
    table('bundle-breakdown-whole-build-raw', title='1b. Source-map attribution, whole client build (generated bytes)'),
    table('bundle-breakdown-entry-closure-raw', title='1c. Source-map attribution, entry chunk plus static import closure (generated bytes)'),
    table('assets-js', [r'JS (gzip|requests)$'], '1d. JS requested on a cold direct load, per route (gzip bytes, request count; raw and brotli in results/summary.md)'),
    table('assets-css', [r'CSS (gzip|requests)$'], '1e. CSS requested on a cold direct load, per route'),
    table('worker-bundle', title='2a. Worker bundles (bytes)'),
    table('worker-startup', title='2b. Worker startup CPU (wrangler check startup, ms)'),
    table('coldstart', title='2c. First request after a local server restart (ms)'),
    table('ttfb', title='3a. Warm TTFB per route (ms)'),
    table('ttfb-total', title='3b. Warm full HTML response time per route (ms)'),
    table('html-bytes', title='3c. HTML bytes per route'),
]
for c in ['cpu1-hover0', 'cpu1-hover300', 'cpu4-hover0', 'cpu4-hover300']:
    parts.append(table(f'navigation-{c}-all', title=f'4. Navigation, all steps pooled, {c}'))
parts.append(table('navigation-cpu1-hover0', title='4b. Navigation per step, cpu1-hover0, click to destination content ready (ms)'))
parts.append(table('navigation-cpu4-hover0', title='4c. Navigation per step, cpu4-hover0 (ms)'))
for c in ['cpu1-hover0', 'cpu4-hover0']:
    parts.append(table(f'webvitals-{c}', [r'(LCP|CLS|INP)$'], f'6c. web-vitals over navigation sequences, {c}'))
for c in ['cpu1', 'cpu4']:
    parts.append(table(f'hydration-{c}', [r'(mainThreadTaskMsUntilHydration|scriptEvaluationMsUntilHydration|longTasksBeforeHydration|ScriptDuration|TaskDuration)$'], f'5. Hydration, {c} (ms, long tasks as count)'))
for p in ['mobile', 'desktop']:
    parts.append(table(f'lighthouse-{p}-scores', title=f'6a. Lighthouse {p} scores (0 to 100)', rng=True))
    parts.append(table(f'lighthouse-{p}-timings', title=f'6b. Lighthouse {p} timings (ms, CLS unitless)', rng=True))
print('\n'.join(parts))
